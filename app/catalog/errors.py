"""Ожидаемые ошибки синхронизации с сообщениями на русском языке."""


class CatalogError(Exception):
    """Базовая ошибка загрузки каталога."""


class ParseError(CatalogError):
    """Страница не соответствует ожидаемой структуре каталога."""


class FetchError(CatalogError):
    """Страницу не удалось получить после ограниченного числа попыток."""


class AccessRestricted(CatalogError):
    """Сайт ограничил доступ; синхронизацию необходимо остановить."""
